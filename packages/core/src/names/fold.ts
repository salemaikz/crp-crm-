// Свёртка букв для сравнения: ё → е и казахские буквы → ближайшие русские, чтобы
// «Қурылыс» и «Курылыс», «Нұр» и «Нур» давали один ключ дедупа.

const KZ_FOLD: Readonly<Record<string, string>> = {
  ё: 'е',
  ә: 'а',
  і: 'и',
  ө: 'о',
  ү: 'у',
  ұ: 'у',
  қ: 'к',
  ғ: 'г',
  ң: 'н',
  һ: 'х',
};

/** Нижний регистр + свёртка. Регистр — до свёртки: «І», «Қ» и т. п. сначала становятся строчными. */
export function foldLetters(s: string): string {
  return s.toLowerCase().replace(/[ёәіөүұқғңһ]/g, (c) => KZ_FOLD[c] ?? c);
}

/** Всё, что не буква и не цифра (кавычки, дефисы, точки, скобки), — пробел; пробелы схлопнуты. */
export function squashSeparators(s: string): string {
  return s.replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
}
