// Формы собственности для нормализации названий. Список приходит параметром из настроек;
// DEFAULT_LEGAL_FORMS — значение по умолчанию продукта (РК: ТОО, ИП, АО и их казахские формы). Ключи и
// признак `idIsPersonal` совпадают с пресетом kz (`global.org.legalForms`), тест — presetKz.test.ts.
// Источник: SalemAI 108fb70 src/lib/crm/coldImport.ts (OPF, OPF_SHORT).

export interface LegalForm {
  /** Ключ формы (для правил отбраковки вроде «только ИП»). */
  key: string;
  /** Полные названия (любой регистр, любая буква ё/е). */
  full: readonly string[];
  /**
   * Аббревиатуры, как отдельное слово. Первая — код формы для правил и профиля (`тоо`, `ип`); пусто —
   * код по первой из `typeOnly`.
   */
  short: readonly string[];
  /**
   * Аббревиатуры, которые признаются формой только в колонке «Тип», но не в названии: в названии они
   * значат другое («ЖК» в «ЖК Альфа Парк» — жилой комплекс, а не «жеке кәсіпкер»).
   */
  typeOnly?: readonly string[];
  /**
   * 12 цифр у этой формы — ИИН человека, а не БИН (D-052): хранится только HMAC. Как `idIsPersonal` в
   * `global.org.legalForms`. Профиль импорта может добавить «личные» формы (`personalIdForms`), но не снять.
   */
  idIsPersonal?: boolean;
}

