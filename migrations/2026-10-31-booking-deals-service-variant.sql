-- Вариант услуги в покупке (D-357, уточняет D-348; docs/pv2-round3.md §4.3). Покупка услуги с вариантами
-- (`serviceTypes[].variants[]`, у первого клиента — онлайн и офлайн) запоминает ключ выбранного варианта, чтобы плитка
-- колонки «Покупка», «Мои покупки» и карточка показывали «{услуга} · {вариант} · {сумма}». Пусто — вариант не выбран:
-- услуга без вариантов, «Другая услуга» или покупка до этой миграции (обратного заполнения нет: по сумме вариант
-- не восстановить — скидка меняет сумму). Сумма по-прежнему в `amount_kzt`, вариант её не задаёт и не проверяет.
-- ПДн нет. Добавляющая и идемпотентная правка: прежняя версия колонку не читает и не пишет (D-059, D-060);
-- `ADD COLUMN … NOT NULL DEFAULT ''` с постоянным умолчанием на Postgres 16 не переписывает таблицу.
ALTER TABLE deals ADD COLUMN IF NOT EXISTS service_variant_key TEXT NOT NULL DEFAULT ''
  CONSTRAINT deals_service_variant_key_check CHECK (service_variant_key ~ '^([a-z0-9_]{1,64})?$');
